CREATE TABLE IF NOT EXISTS aircrafts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    model VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS airports (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    airport_name VARCHAR(255),
    code VARCHAR(5) UNIQUE,
    city VARCHAR(255),
    country VARCHAR(255)

);

CREATE TABLE IF NOT EXISTS users(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name VARCHAR(50),
    last_name VARCHAR(50),
    email VARCHAR(255) UNIQUE
);


CREATE TABLE IF NOT EXISTS passengers(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name VARCHAR(50),
    last_name VARCHAR(50)
);

CREATE TABLE IF NOT EXISTS seats(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    seat_number VARCHAR(10),
    aircraft_id BIGINT,
    seat_class VARCHAR(20),
    FOREIGN KEY (aircraft_id) REFERENCES aircrafts(id),
    CONSTRAINT uq_aircraft_seat UNIQUE (seat_number, aircraft_id)
);


CREATE TABLE IF NOT EXISTS flights (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    flight_number VARCHAR(255),
    aircraft_id BIGINT,
    departure_airport_id BIGINT,
    arrival_airport_id BIGINT,
    departure_time timestamp,
    arrival_time timestamp,
    FOREIGN KEY  (aircraft_id) REFERENCES aircrafts(id),
    FOREIGN KEY  (departure_airport_id) REFERENCES airports(id),
    FOREIGN KEY  (arrival_airport_id) REFERENCES airports(id)
);


CREATE TABLE IF NOT EXISTS flight_seats(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    flight_id BIGINT,
    seat_id BIGINT,
    price NUMERIC(12,2),
    status VARCHAR(255),
    FOREIGN KEY (flight_id) REFERENCES flights(id),
    FOREIGN KEY (seat_id) REFERENCES seats(id),
    CONSTRAINT uq_seats UNIQUE(flight_id, seat_id)
);




CREATE TABLE IF NOT EXISTS bookings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    flight_seat_id BIGINT,
    user_id BIGINT,
    expiration_date timestamp,
    is_paid BOOLEAN,
    FOREIGN KEY (flight_seat_id) REFERENCES flight_seats(id),
    FOREIGN KEY (user_id) REFERENCES users(id)
);

CREATE TABLE IF NOT EXISTS tickets(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id BIGINT UNIQUE,
    passenger_id BIGINT,
    ticket_number VARCHAR(255),
    FOREIGN KEY (booking_id) REFERENCES bookings(id),
    FOREIGN KEY (passenger_id) REFERENCES passengers(id)
);








